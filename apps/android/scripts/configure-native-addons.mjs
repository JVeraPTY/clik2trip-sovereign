import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const require = createRequire(import.meta.url);

const qvacManifestPath = path.join(projectRoot, 'qvac', 'addons.manifest.json');
const qvacBundlePath = path.join(projectRoot, 'qvac', 'worker.bundle.js');
const wdkBundlePath = path.join(
  projectRoot,
  '.wdk-bundle',
  'wdk-worklet.bundle.js',
);

if (!fs.existsSync(qvacManifestPath) || !fs.existsSync(qvacBundlePath)) {
  throw new Error(
    'QVAC_BUNDLE_OR_MANIFEST_NOT_FOUND: run the QVAC Expo prebuild before configuring native addons',
  );
}

if (!fs.existsSync(wdkBundlePath)) {
  throw new Error(
    'WDK_BUNDLE_NOT_FOUND: run `pnpm wdk:bundle` before the Android prebuild',
  );
}

const manifest = JSON.parse(fs.readFileSync(qvacManifestPath, 'utf8'));

function readBundleHeader(bundlePath) {
  const bundle = require(bundlePath);
  if (typeof bundle !== 'string') {
    throw new Error(`INVALID_BARE_BUNDLE_EXPORT: ${bundlePath}`);
  }

  const firstNewline = bundle.indexOf('\n');
  const headerLength = Number(bundle.slice(0, firstNewline));
  if (firstNewline < 1 || !Number.isSafeInteger(headerLength)) {
    throw new Error(`INVALID_BARE_BUNDLE_HEADER: ${bundlePath}`);
  }

  return JSON.parse(bundle.slice(firstNewline + 1, firstNewline + headerLength));
}

function collectLinkedAddons(bundlePath, bundleProjectRoot) {
  const header = readBundleHeader(bundlePath);
  const descriptors = new Map();

  for (const resolution of Object.values(header.resolutions ?? {})) {
    const packageVirtualPath = resolution['#package'];
    if (typeof packageVirtualPath !== 'string') continue;

    for (const target of Object.values(resolution)) {
      const linked =
        typeof target === 'string'
          ? target
          : target && typeof target === 'object'
            ? target.android
            : undefined;
      if (typeof linked !== 'string' || !linked.startsWith('linked:lib')) {
        continue;
      }

      const library = linked.slice('linked:'.length);
      const packageJsonPath = path.resolve(
        bundleProjectRoot,
        `.${packageVirtualPath}`,
      );
      if (!fs.existsSync(packageJsonPath)) {
        throw new Error(`LINKED_ADDON_PACKAGE_NOT_FOUND: ${packageJsonPath}`);
      }

      const addonPackage = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
      const descriptor = {
        directory: path.dirname(packageJsonPath),
        library,
        name: addonPackage.name,
        version: addonPackage.version,
      };
      descriptors.set(`${descriptor.directory}:${library}`, descriptor);
    }
  }

  return [...descriptors.values()];
}

const repositoryRoot = path.resolve(projectRoot, '../..');
const qvacLinkedAddons = collectLinkedAddons(qvacBundlePath, projectRoot);
const wdkLinkedAddons = collectLinkedAddons(wdkBundlePath, repositoryRoot);
const linkedAddons = [
  ...new Map(
    [...qvacLinkedAddons, ...wdkLinkedAddons].map((addon) => [
      `${addon.directory}:${addon.library}`,
      addon,
    ]),
  ).values(),
];
const wdkAddons = [...new Set(wdkLinkedAddons.map((addon) => addon.name))];

if (wdkAddons.length === 0) {
  throw new Error('WDK_ADDONS_NOT_FOUND_IN_BUNDLE');
}

if (qvacLinkedAddons.length === 0) {
  throw new Error('QVAC_ADDONS_NOT_FOUND_IN_BUNDLE');
}

const addons = [
  ...new Set([...(Array.isArray(manifest.addons) ? manifest.addons : []), ...wdkAddons]),
].sort();

fs.writeFileSync(
  qvacManifestPath,
  `${JSON.stringify({ ...manifest, addons }, null, 2)}\n`,
);

const bareKitPackagePath = require.resolve('react-native-bare-kit/package.json');
const bareKitAndroidDirectory = path.join(
  path.dirname(bareKitPackagePath),
  'android',
);
const linkerPath = path.join(bareKitAndroidDirectory, 'link.mjs');
const relativeProjectRoot = path.relative(bareKitAndroidDirectory, projectRoot);
const addonDirectories = [
  ...new Set(
    linkedAddons.map((addon) => path.relative(projectRoot, addon.directory)),
  ),
].sort();
const expectedLibraries = [
  ...new Set(linkedAddons.map((addon) => addon.library)),
].sort();

const linker = `/**
 * Generated by apps/android/scripts/configure-native-addons.mjs.
 * Links the exact QVAC and WDK addon versions referenced by both bundles.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import link from 'bare-link'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, ${JSON.stringify(relativeProjectRoot)})
const addonsDir = path.join(__dirname, 'src', 'main', 'addons')
const addonDirectories = ${JSON.stringify(addonDirectories, null, 2)}
const expectedLibraries = ${JSON.stringify(expectedLibraries, null, 2)}

fs.rmSync(addonsDir, { recursive: true, force: true })

console.log(\`[Clik2Trip] Linking \${addonDirectories.length} exact QVAC/WDK addon packages for Android ARM64\`)

for (const addonDirectory of addonDirectories) {
  for await (const resource of link(path.resolve(projectRoot, addonDirectory), {
    hosts: ['android-arm64'],
    out: addonsDir
  })) {
    console.log('Wrote', resource)
  }
}

const generatedDirectory = path.join(addonsDir, 'arm64-v8a')
const generatedLibraries = new Set(fs.readdirSync(generatedDirectory))
const missingLibraries = expectedLibraries.filter(
  (library) => !generatedLibraries.has(library)
)

if (missingLibraries.length > 0) {
  throw new Error(\`NATIVE_ADDON_VERSION_MISMATCH: \${missingLibraries.join(', ')}\`)
}
`;

fs.writeFileSync(linkerPath, linker);

console.log(
  `[Clik2Trip] Native addon linker ready: ${addonDirectories.length} exact package roots, ${expectedLibraries.length} required libraries`,
);
